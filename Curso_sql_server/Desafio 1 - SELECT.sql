/*-- DESAFIO --

RECUPERE AS INFORMAÇÕES DA TABELA DE ENTIDADES TRAZENDO APENAS AS COLUNAS
1. ENTIDADE
2. NOME
3. INSCRICAO_FEDERAL
4. ATIVO

E UTILIZE OS SEGUINTES ALIAS PARA CADA COLUNA:

PARA A COLUNA ENTIDADE UTILIZA O ALIAS COD_CLIENTE,
A COLUNA NOME PODE PERMANECER COMO NOME,
PARA A COLUNA INSCRICAO_FEDERAL USE O ALIAS CPF_CNPJ E POR FIM
PARA A COLUNA ATIVO USE O ALIAS CADASTRO_ATIVO
*/

SELECT	ENTIDADE AS COD_CLIENTE
,		NOME AS NOME_CLIENTE
,		INSCRICAO_FEDERAL AS CPF_CNPJ
,		ATIVO AS CADASTRO_ATIVO
FROM	ENTIDADES
WHERE ATIVO = 'S'
ORDER BY NOME ASC;